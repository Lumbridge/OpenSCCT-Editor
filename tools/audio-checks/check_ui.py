"""Exercise the real editor through its isolated background session's synthetic UI input."""
import json
import pathlib
import socket
import sys
import time

run = pathlib.Path(sys.argv[1]).resolve()
deadline = time.monotonic() + 30
while not (discovery := list((run / "live").glob("editor-*.json"))):
    if time.monotonic() > deadline:
        raise RuntimeError("The background editor did not publish its live connection within 30 seconds")
    time.sleep(0.1)
meta = json.loads(discovery[0].read_text())
sock = socket.create_connection(("127.0.0.1", meta["port"]), timeout=60)
stream = sock.makefile("rwb")
stream.write((json.dumps(dict(auth=meta["token"], client="sound-ui-regression")) + "\n").encode())
stream.flush()
assert json.loads(stream.readline())["ok"]
sequence = 0


def call(method, params=None):
    global sequence
    sequence += 1
    stream.write((json.dumps(dict(id=sequence, method=method, params=params or {})) + "\n").encode())
    stream.flush()
    reply = json.loads(stream.readline())
    assert "error" not in reply, reply
    return reply["result"]


def step(op, **args):
    return call("ui.input", dict(steps=[dict(op=op, frames=5, **args)]))


def controls():
    return call("ui.tree", dict(limit=1600))["controls"]


def shot(name):
    result = call("ui.shot", dict(name=name, dir=str(run)))
    assert not result["lint"], result["lint"]
    return result["path"]


def objects():
    return call("query", dict(q="find", fields=["id", "class", "props"]))["items"]


def props(actor_id):
    return next(a["props"] for a in objects() if a["id"] == actor_id)


def action(title):
    step("key", key="Ctrl+Shift+P")
    step("type", text=title)
    step("key", key="Enter")


assert call("editor")["map"] == "SoundDemo", "Use the disposable fixture generated by AudioChecks"
step("click", at="action:sound.library")
source = next(a["id"] for a in objects() if a["class"] == "Engine.AmbientSound")
call("apply", dict(ops=[dict(op="select", id=source)]))
mute = next(c for c in controls() if c.get("action") == "audio.mute").get("pressed", False)
step("click", at="action:audio.mute")
assert next(c for c in controls() if c.get("action") == "audio.mute").get("pressed", False) != mute
step("click", at="action:audio.mute")
print("PASS toolbar mute toggles and restores its state")

step("click", at="text:Loop Preview")
step("click", at="text:Play")
assert any(c.get("text") == "Pause" for c in controls())
step("click", at="text:Pause")
assert any(c.get("text") == "Resume" for c in controls())
step("click", at="text:Resume")
wave = next(c for c in controls() if c["path"].endswith("/SoundWaveform"))
step("click", at=wave["path"], offset=[0.6, 0.5])
shot("sounds-playing")
step("click", at="text:Stop")
assert any(c.get("text") == "Play" for c in controls())
print("PASS preview play, pause, resume, waveform seek and stop")

old_radius = props(source)["SoundRadius"]
step("click", at="text:Room")
step("click", at="text:Apply to Selected")
assert props(source)["SoundRadius"] == 24
step("click", at="action:edit.undo")
assert props(source)["SoundRadius"] == old_radius
step("click", at="text:Remove Sound")
assert props(source).get("AmbientSound") is None
step("click", at="action:edit.undo")
assert props(source)["AmbientSound"]["$asset"]
print("PASS reach preset, apply, remove and undo")

count = len(objects())
step("click", at="text:Place at Brush")
assert len(objects()) == count + 1 and call("editor")["selectionCount"] == 1
placed = call("editor")["selection"][0]
call("apply", dict(ops=[dict(op="select", ids=[source, placed])]))
step("click", at="text:Room")
step("click", at="text:Apply to Selected")
assert props(source)["SoundRadius"] == 24 and props(placed)["SoundRadius"] == 24
step("click", at="action:edit.undo")
assert props(source)["SoundRadius"] == old_radius
step("click", at="action:edit.undo")
assert len(objects()) == count
print("PASS place source at brush, batch editing and undo")

search = next(c for c in controls() if c["path"].endswith("/SoundSearch"))
step("click", at=search["path"])
step("key", key="Ctrl+A")
step("type", text="TestTone")
tree = next(c for c in controls() if c["type"] == "Tree" and c["path"].endswith("/Library"))
x, y, w, h = tree["rect"]
step("drag", at=[x + 80, y + 38], to="view:Perspective", toOffset=[0.7, 0.55], steps=24, hold=4)
assert len(objects()) == count + 1, "Dragging a sound into the viewport must place it"
assert props(call("editor")["selection"][0])["SoundRadius"] == old_radius, "Dragging from Sounds carries the current settings"
step("click", at="action:edit.undo")
assert len(objects()) == count
print("PASS drag-and-drop sound placement and undo")

call("apply", dict(ops=[dict(op="select", id=source)]))
step("click", at="text:Listen in Map")
assert any(c.get("text") == "Listen in Map" and c.get("pressed") for c in controls())
step("click", at="text:Solo Selected")
assert any(c.get("text") == "Solo Selected" and c.get("pressed") for c in controls())
step("click", at="text:Listen in Map")
print("PASS map audition and solo controls")

# Capture the particle scene both with and without effects for visual comparison.
call("apply", dict(ops=[dict(op="select", mode="clear")]))
step("escape")
shot("particles-visible")
action("Particle Effects")
shot("particles-hidden")
action("Particle Effects")
action("Pause Particle Preview")
shot("particles-paused")
call("ui.input", dict(steps=[dict(op="escape", frames=45)]))
shot("particles-paused-later")
action("Pause Particle Preview")
action("Replay Map Emitters")
print("PASS particle show, pause and replay actions")

step("click", at="action:emitter.library")
shot("emitter-library")
step("click", at="action:sound.library")
call("apply", dict(ops=[dict(op="select", id=source)]))
step("escape")
shot("sounds-final")
action("150%")
shot("sounds-150")
assert next(c for c in controls() if c.get("action") == "audio.mute")["rect"][0] < call("ui.tree")["canvas"][0]
action("100%")
print("PASS sound controls and toolbar fit at 150% UI scale")
print("PASS sound and emitter UI checks; review screenshots in", run)
stream.close()
sock.close()
